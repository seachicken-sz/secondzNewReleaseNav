// Draw the share image with native Canvas (safe for iOS Safari).
// Assets are same-origin SVGs stored in img/image parts, not off-screen HTML.
const FILES={
  purplePink:{
    tile:"theme1/background-tile.svg",
    top:"theme1/ribbon.svg",
    left:"theme1/tape-purple.svg",
    right:"theme1/tape-pink.svg",
    sparkle:"theme1/sparkles.svg"
  },
  movieMint:{
    tile:"theme2/background-tile.svg",
    top:"theme2/movie-camera.svg",
    strip:"theme2/film-strip.svg",
    reel:"theme2/film-reel.svg",
    paw:"theme2/paw-prints.svg"
  }
};
const cache=new Map();
const imageUrl=path=>new URL("../img/image%20parts/"+path,import.meta.url).href;
const loadImage=path=>{
  if(!cache.has(path)){
    const promise=new Promise((resolve,reject)=>{
      const image=new Image();
      image.onload=()=>resolve(image);
      image.onerror=()=>reject(new Error("画像パーツを読み込めませんでした: "+path));
      image.src=imageUrl(path);
    }).catch(error=>{cache.delete(path);throw error});
    cache.set(path,promise);
  }
  return cache.get(path);
};
async function loadTheme(theme){
  const descriptors=FILES[theme]||FILES.purplePink;
  const result={};
  // Missing decorations must not blank the exported image.
  await Promise.all(Object.entries(descriptors).map(async([name,path])=>{
    try{result[name]=await loadImage(path)}
    catch(error){console.warn(error);result[name]=null}
  }));
  return result;
}
const roundPath=(g,x,y,w,h,r)=>{
  const radius=Math.min(r,w/2,h/2);
  g.beginPath();g.moveTo(x+radius,y);g.lineTo(x+w-radius,y);
  g.quadraticCurveTo(x+w,y,x+w,y+radius);
  g.lineTo(x+w,y+h-radius);g.quadraticCurveTo(x+w,y+h,x+w-radius,y+h);
  g.lineTo(x+radius,y+h);g.quadraticCurveTo(x,y+h,x,y+h-radius);
  g.lineTo(x,y+radius);g.quadraticCurveTo(x,y,x+radius,y);
  g.closePath();
};
const panel=(g,x,y,w,h,r,fill,border)=>{
  roundPath(g,x,y,w,h,r);
  if(fill){g.fillStyle=fill;g.fill()}
  if(border){g.lineWidth=2.5;g.strokeStyle=border;g.stroke()}
};
const asset=(g,img,x,y,w,h,opacity=1,angle=0)=>{
  if(!img)return;
  g.save();g.globalAlpha=opacity;
  g.translate(x+w/2,y+h/2);g.rotate(angle);
  g.drawImage(img,-w/2,-h/2,w,h);
  g.restore();
};
const ticket=(g,x,y,w,h,bg,border)=>{
  // The ticket geometry is generated by Canvas and stretches with the rows.
  g.save();
  panel(g,x,y,w,h,20,bg,border);
  // Notches on both sides, clipped to the ticket border.
  g.fillStyle="#fffdf4";
  for(const yy of [y+28,y+h-28]){
    g.beginPath();g.arc(x,yy,12,0,Math.PI*2);g.fill();
    g.beginPath();g.arc(x+w,yy,12,0,Math.PI*2);g.fill();
  }
  g.strokeStyle=border;g.lineWidth=1.4;g.setLineDash([4,9]);
  g.beginPath();g.moveTo(x+12,y+16);g.lineTo(x+12,y+h-16);
  g.moveTo(x+w-12,y+16);g.lineTo(x+w-12,y+h-16);g.stroke();
  g.restore();
};
export async function renderPlanPng({sections,title,releaseTitle,totalCount,totalPrice,colors,theme="purplePink"}){
  await document.fonts?.ready;
  const themeKey=theme==="movieMint"?"movieMint":"purplePink";
  const art=await loadTheme(themeKey);
  const isTicket=themeKey==="movieMint";
  const width=900,margin=38,innerX=79,innerW=742;
  const canvas=document.createElement("canvas");canvas.width=width;
  const measure=canvas.getContext("2d",{alpha:false});
  if(!measure)throw new Error("Canvasを初期化できませんでした");
  const family='"Hiragino Kaku Gothic ProN","Hiragino Sans",-apple-system,BlinkMacSystemFont,sans-serif';
  const font=(size,weight=500)=>weight+" "+size+"px "+family;
  const wrap=(str,max,style)=>{
    measure.font=style;const result=[];let line="";
    for(const char of String(str)){
      if(line&&measure.measureText(line+char).width>max){result.push(line);line=char}
      else line+=char;
    }
    if(line)result.push(line);
    return result.length?result:[""];
  };
  const titleLines=wrap(title,innerW-70,font(40,750));
  const releaseLines=wrap(releaseTitle,innerW-80,font(21));
  const groups=sections.map(section=>{
    const heading=wrap(section.title,innerW-90,font(26,750));
    const rows=section.entries.map(([label,value])=>{
      const lines=wrap(label,innerW-190,font(22));
      return {lines,value,height:Math.max(53,lines.length*32+19)};
    });
    return {heading,rows,height:29+heading.length*39+15+rows.reduce((n,r)=>n+r.height,0)+21};
  });
  const topHeight=155+55+35+titleLines.length*57+15+releaseLines.length*34+42;
  const groupHeight=groups.reduce((n,group)=>n+group.height+21,0);
  const footerHeight=188;
  const imageHeight=Math.max(940,margin+topHeight+groupHeight+footerHeight+margin);
  canvas.height=imageHeight;
  const g=canvas.getContext("2d",{alpha:false});
  if(!g)throw new Error("Canvasを初期化できませんでした");
  const drawText=(value,x,y,size,weight=500,color="#40334a",align="left")=>{
    g.font=font(size,weight);g.textAlign=align;g.textBaseline="top";g.fillStyle=color;g.fillText(String(value),x,y);
  };
  const twinkle=(x,y,r,color)=>{
    g.fillStyle=color;g.beginPath();g.moveTo(x,y-r);g.quadraticCurveTo(x+r*.2,y-r*.2,x+r,y);
    g.quadraticCurveTo(x+r*.2,y+r*.2,x,y+r);g.quadraticCurveTo(x-r*.2,y+r*.2,x-r,y);
    g.quadraticCurveTo(x-r*.2,y-r*.2,x,y-r);g.fill();
  };
  // Repeat the seamless tile across any image height; allow a color fallback if it cannot load.
  g.fillStyle=colors.bg;g.fillRect(0,0,width,imageHeight);
  if(art.tile){
    g.save();g.globalAlpha=isTicket?.47:.54;
    const pattern=g.createPattern(art.tile,"repeat");
    if(pattern){g.fillStyle=pattern;g.fillRect(0,0,width,imageHeight)}
    g.restore();
  }
  panel(g,margin,margin,width-2*margin,imageHeight-2*margin,38,
    isTicket?"#FFFDF3":"#FFF9FD",colors.border);
  // Retain a small patterned edge inside the outer frame, without painting over text.
  if(art.tile){
    g.save();g.globalAlpha=.29;
    roundPath(g,margin+6,margin+6,width-2*margin-12,imageHeight-2*margin-12,32);
    g.clip();const pattern=g.createPattern(art.tile,"repeat");
    if(pattern){g.fillStyle=pattern;g.fillRect(margin+6,margin+6,width-2*margin-12,imageHeight-2*margin-12)}
    g.restore();
  }
  if(isTicket){
    asset(g,art.strip,-15,15,335,142,.75,-.10);
    asset(g,art.top,420,48,62,64,.95);
    asset(g,art.reel,36,imageHeight-193,146,145,.92);
    asset(g,art.paw,width-295,imageHeight-175,256,127,.96);
  }else{
    asset(g,art.top,290,52,320,125,.98);
    asset(g,art.sparkle,55,136,185,95,.63);
    asset(g,art.sparkle,653,145,174,96,.56);
  }
  let y=isTicket?122:183;
  if(isTicket)y+=40;
  drawText("MY CD PURCHASE PLAN",width/2,y,19,750,colors.accent,"center");y+=40;
  for(const line of titleLines){drawText(line,width/2,y,40,750,colors.accent,"center");y+=57}
  y+=13;
  for(const line of releaseLines){drawText(line,width/2,y,21,500,colors.accent,"center");y+=34}
  y+=44;
  for(const [groupIndex,group] of groups.entries()){
    const color=isTicket?colors.border:groupIndex%2===0?colors.border:colors.pink||colors.border;
    if(isTicket)ticket(g,innerX,y,innerW,group.height,"#FFFDF5",color);
    else{
      g.save();g.shadowColor="#D5B5DF";g.shadowBlur=12;g.shadowOffsetY=4;
      panel(g,innerX,y,innerW,group.height,23,"#FFFCFF",color);
      g.restore();
      asset(g,art.left,innerX-20,y-15,140,42,.94,-.22);
      asset(g,art.right,innerX+innerW-116,y-13,128,38,.95,.17);
    }
    let ry=y+29;
    for(const line of group.heading){drawText(line,innerX+27,ry,26,750,colors.accent);ry+=39}
    ry+=15;
    for(const row of group.rows){
      g.save();g.strokeStyle=isTicket?"#B7DED4":colors.border;g.lineWidth=1;
      g.setLineDash([7,7]);g.beginPath();g.moveTo(innerX+23,ry-7);g.lineTo(innerX+innerW-23,ry-7);g.stroke();g.restore();
      row.lines.forEach((line,index)=>drawText(line,innerX+27,ry+3+index*32,22,500,"#463950"));
      if(isTicket){
        panel(g,innerX+innerW-135,ry+1,111,35,18,"#DDF5EC",null);
      }else{
        panel(g,innerX+innerW-135,ry+1,111,35,18,colors.soft,null);
      }
      drawText(row.value,innerX+innerW-29,ry+5,22,750,colors.accent,"right");
      ry+=row.height;
    }
    y+=group.height+21;
  }
  // Summary panel: variable-height content above, fixed-size decoration below.
  const summaryY=y+5;
  if(isTicket)ticket(g,innerX,summaryY,innerW,110,"#FFF9DE",colors.border);
  else{
    panel(g,innerX,summaryY,innerW,110,20,"#FDECF5",colors.pink);
    asset(g,art.left,innerX-14,summaryY-11,106,34,.88,-.20);
    asset(g,art.right,innerX+innerW-89,summaryY+84,103,33,.86,-.18);
  }
  if(isTicket){
    g.save();g.strokeStyle=colors.border;g.setLineDash([4,9]);g.beginPath();
    g.moveTo(innerX+innerW/2,summaryY+12);g.lineTo(innerX+innerW/2,summaryY+97);g.stroke();g.restore();
  }else{
    twinkle(innerX+24,summaryY+24,12,colors.pink);
    twinkle(innerX+innerW-24,summaryY+80,11,colors.accent);
  }
  drawText("CD合計",innerX+28,summaryY+18,19,750,colors.accent);
  drawText(totalCount+"枚",innerX+28,summaryY+52,35,750,colors.accent);
  drawText("合計金額",innerX+innerW-27,summaryY+18,19,750,colors.accent,"right");
  drawText(totalPrice.toLocaleString("ja-JP")+"円",innerX+innerW-27,summaryY+52,35,750,colors.accent,"right");
  const creditY=summaryY+139;
  drawText("タムごと新曲応援ナビ",width/2,creditY,21,750,colors.accent,"center");
  if(!isTicket){twinkle(237,creditY+11,11,colors.pink);twinkle(660,creditY+11,11,colors.pink)}
  const blob=await new Promise((resolve,reject)=>{
    canvas.toBlob(value=>value?resolve(value):reject(new Error("PNGを生成できませんでした")),"image/png");
  });
  if(blob.size<2000)throw new Error("画像データが正常に作成されませんでした");
  return blob;
}
